public class Principal {
    public static void main(String[] args) {
        // Exemplo com println (com quebra de linha)
        System.out.println("Olá, mundo!");

        // Exemplo com print (na mesma linha)
        System.out.print("Texto 1 ");
        System.out.print("Texto 2");

        // Exemplo com printf (formatado)
        String nome = "Maria";
        int idade = 30;
        System.out.printf("%nNome: %s, Idade: %d", nome, idade);
    }
}
